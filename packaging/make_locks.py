"""Download the runtime wheels with their dependencies (binary only) and write the hashed locks.
Usage: .venv/bin/python packaging/make_locks.py
Out: build/wheels-win, build/wheels-mac, packaging/requirements-win.lock, packaging/requirements-mac.lock.
The sha256 of every wheel is compared with the PyPI JSON API (no trust in the local download alone)."""
import hashlib
import json
import shutil
import subprocess
import sys
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
pins = [l.split("#")[0].strip() for l in (ROOT / "packaging/requirements.in").read_text().splitlines()]
pins = [p for p in pins if p]
TARGETS = {"win": ("win_amd64", "CPython 3.13 win_amd64", True),
           "mac": ("macosx_14_0_arm64", "CPython 3.13 macosx_arm64", False)}

for name, (plat, label, windows) in TARGETS.items():
    reqs = [p.split(";")[0].strip() for p in pins if windows or "win32" not in p]
    d = ROOT / "build" / ("wheels-" + name)
    shutil.rmtree(d, ignore_errors=True)
    subprocess.run([sys.executable, "-m", "pip", "download", "-q", "--only-binary=:all:", "--platform", plat,
                    "--python-version", "3.13", "--implementation", "cp", "-d", str(d), *reqs], check=True)
    lines = ["# HatirMail worker lock for %s. Generated by packaging/make_locks.py from packaging/requirements.in." % label,
             "# Install: python -m pip install --no-index --find-links <wheels> --require-hashes -r <this file>"]
    for whl in sorted(d.glob("*.whl"), key=lambda w: w.name.lower()):
        pkg, ver = whl.name.split("-")[:2]
        h = hashlib.sha256(whl.read_bytes()).hexdigest()
        # Fixed https:// URL; pkg and ver come from the wheel file names that pip downloaded.
        meta = json.load(urllib.request.urlopen("https://pypi.org/pypi/%s/%s/json" % (pkg, ver), timeout=60))  # nosemgrep: dynamic-urllib-use-detected
        assert any(u["filename"] == whl.name and u["digests"]["sha256"] == h for u in meta["urls"]), whl.name
        lines += ["%s==%s \\" % (pkg.replace("_", "-"), ver), "    --hash=sha256:%s" % h]
    (ROOT / "packaging" / ("requirements-%s.lock" % name)).write_text("\n".join(lines) + "\n")
    whls = list(d.glob("*.whl"))
    print(name, len(whls), "wheels,", round(sum(w.stat().st_size for w in whls) / 2**20, 1), "MB")
